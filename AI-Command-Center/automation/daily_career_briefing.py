"""
Daily Career Intelligence Morning Briefing Generator
Generates an executive daily action queue answering the 5 core questions:
1. Top 3 highest-priority roles to target today
2. High-fit opportunities needing tailored outreach
3. Follow-up and interview preparation items
4. Measurable pipeline progress
"""

import json
import os
import sqlite3
from datetime import datetime

VAULT_PATH = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__),
        "..",
        "projects",
        "flagship-career-engine",
        "career_vault.db",
    )
)
OUTPUT_PATH = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "DAILY_BRIEFING.md")
)


def generate_briefing():
    if not os.path.exists(VAULT_PATH):
        print(f"[ERROR] Database not found at {VAULT_PATH}")
        return

    conn = sqlite3.connect(VAULT_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM jobs ORDER BY fit_score DESC, created_at DESC")
    all_jobs = [dict(r) for r in cursor.fetchall()]

    today_str = datetime.now().strftime("%Y-%m-%d")
    cursor.execute(
        """
        SELECT a.*, j.url, j.location, j.fit_score 
        FROM applications a
        LEFT JOIN jobs j ON a.job_id = j.job_id
        WHERE a.follow_up_date <= ? AND a.outreach_status != 'FOLLOWED_UP'
        ORDER BY a.follow_up_date ASC
    """,
        (today_str,),
    )
    due_follow_ups = [dict(r) for r in cursor.fetchall()]

    cursor.execute("SELECT COUNT(*) FROM applications")
    total_applied = cursor.fetchone()[0]
    conn.close()

    total_jobs = len(all_jobs)
    high_fit = [j for j in all_jobs if j["fit_score"] >= 80]
    top_3 = high_fit[:3]

    timestamp = datetime.now().strftime("%A, %d %B %Y — %I:%M %p")

    briefing_md = f"""# DAILY CAREER COMMAND BRIEFING
**Date:** {timestamp}  
**Candidate:** Aditya Mehra | BBA International Business (DSU '26)  
**Target:** Bangalore Business Operations & Supply Chain (Non-Sales)  

---

## 1. Today's Top 3 Priority Applications

"""
    for idx, j in enumerate(top_3, 1):
        briefing_md += f"""### {idx}. {j["company"]} — {j["title"]}
- **Fit Score:** `{j["fit_score"]}/100` | **Requisition ID:** `{j["job_id"]}`
- **Location:** {j["location"]} | **Department:** {j["department"]}
- **Direct Portal Link:** [{j["url"]}]({j["url"]})
- **Application Documents:**
  - Standard ATS Word: [`ADITYA_MEHRA_MASTER_ATS_RESUME.docx`](career/ADITYA_MEHRA_MASTER_ATS_RESUME.docx)
  - Standard ATS PDF: [`ADITYA_MEHRA_MASTER_ATS_RESUME.pdf`](career/ADITYA_MEHRA_MASTER_ATS_RESUME.pdf)
- **Recommended Action:** Submit formal application and send personalized outreach to HR via [`index.html`](projects/flagship-career-engine/index.html).

"""

    briefing_md += """---

## 2. Follow-Up Queue & Actionable Reminders

"""
    if due_follow_ups:
        for fup in due_follow_ups:
            briefing_md += f"""- [ ] **Follow Up Due ({fup["follow_up_date"]}):** {fup["company"]} — *{fup["title"]}* (Applied: {fup["applied_date"]}). Send Day-3 follow-up note.
"""
    else:
        briefing_md += """*No overdue application follow-ups today. Pipeline is current and healthy.*

"""

    briefing_md += f"""---

## 3. Pipeline Summary Telemetry

- **Total Deduplicated Opportunities in Vault:** `{total_jobs}`
- **High-Fit Target Roles (Score >= 80):** `{len(high_fit)}`
- **Total Applications Submitted & Tracked:** `{total_applied}`
- **Disqualified / Cold-Calling Sales Blocked:** `{sum(1 for j in all_jobs if len(json.loads(j["disqualification_flags"])) > 0)}`

---

## 4. Today's Interview Preparation Focus

> **Question of the Day:** *"How do you handle a vendor who fails to deliver as per SLA?"*  
> **Grounded STAR Response:** Benchmark vendor line items against pre-agreed master SLAs, isolate unjustified surcharges, and deploy contingency backup suppliers (Preserved gross margin across 300+ live Bangalore events).  
> **Full STAR Playbook:** Available in [`career/INTERVIEW_PLAYBOOK.md`](career/INTERVIEW_PLAYBOOK.md).

---

## 5. Daily Action Checklist

- [ ] **Step 1:** Review Requisition #1 ({top_3[0]["company"]} - {top_3[0]["title"]}) and submit formal application.
- [ ] **Step 2:** Copy tailored outreach message from [`index.html`](projects/flagship-career-engine/index.html) and connect with in-house HR on LinkedIn.
- [ ] **Step 3:** Review Requisition #2 ({top_3[1]["company"]} - {top_3[1]["title"]}) and submit formal application.
- [ ] **Step 4:** Run [`automation/backup_vault.py`](automation/backup_vault.py) to preserve today's pipeline state.

---
*Generated by Antigravity Omnisystem Automation Engine.*
"""

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(briefing_md)
    print(f"[OK] Daily briefing generated successfully at: {OUTPUT_PATH}")


if __name__ == "__main__":
    generate_briefing()
