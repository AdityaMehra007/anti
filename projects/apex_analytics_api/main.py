import os
import sqlite3
from fastapi import FastAPI

app = FastAPI(title="apex_analytics_api", version="1.1.0")

DB_PATH = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__), "..", "powerbi_model", "vendor_sla_bi_model.db"
    )
)


@app.get("/")
def read_root():
    return {"service": "apex_analytics_api", "status": "ONLINE", "runtime": "APEX_HOSTED"}


@app.get("/health")
def health_check():
    return {"status": "HEALTHY"}


@app.get("/metrics")
def get_operational_metrics():
    if not os.path.exists(DB_PATH):
        return {
            "service": "apex_analytics_api",
            "db_status": "NOT_INITIALIZED",
            "total_incidents": 0,
        }

    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()
        total_incidents = cur.execute("SELECT COUNT(*) FROM fact_vendor_sla").fetchone()[0]
        breaches = cur.execute("SELECT COUNT(*) FROM fact_vendor_sla WHERE breach_flag = 1").fetchone()[0]
        penalties = cur.execute("SELECT COALESCE(SUM(penalty_amount_inr), 0) FROM fact_vendor_sla").fetchone()[0]
        vendors = cur.execute("SELECT COUNT(*) FROM dim_vendor").fetchone()[0]
        conn.close()

        return {
            "service": "apex_analytics_api",
            "db_status": "ONLINE",
            "vendors_monitored": vendors,
            "total_incidents": total_incidents,
            "sla_breaches": breaches,
            "breach_rate_pct": round(breaches / max(total_incidents, 1) * 100, 2),
            "total_penalty_recovery_inr": penalties,
        }
    except Exception as e:
        return {"service": "apex_analytics_api", "error": str(e)}
