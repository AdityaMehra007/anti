class ProjectGenerator:
    def __init__(self, workspace_root: Path):
        self.workspace_root = workspace_root

    def scaffold_project(self, project_name: str, objective: str) -> Path:
        proj_dir = self.workspace_root / "apex" / "projects" / project_name
        proj_dir.mkdir(parents=True, exist_ok=True)
        (proj_dir / "src").mkdir(exist_ok=True)
        (proj_dir / "tests").mkdir(exist_ok=True)
        (proj_dir / "docs").mkdir(exist_ok=True)

        readme_content = f"# {project_name}\n\n**Objective:** {objective}\n\nGenerated by APEX V3 Project Generator.\n"
        with open(proj_dir / "README.md", "w", encoding="utf-8") as f:
            f.write(readme_content)

        return proj_dir
